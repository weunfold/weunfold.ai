// Emits tokens.css and tokens.js from tokens.json, so the CSS, the JS and the JSON never drift.
// node design-system/build.mjs          write both files
// node design-system/build.mjs --check  exit 1 if either is stale
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DIR = path.dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(fs.readFileSync(path.join(DIR, "tokens.json"), "utf8"));
const HEAD = "/* Generated by design-system/build.mjs from tokens.json. Do not edit; edit tokens.json and rebuild. */\n";

const themed = (theme) => t.color.tokens.map((c) => [c.name, typeof c.value === "string" ? c.value : c.value[theme]]);
const decl = (pairs, pad = "  ") => pairs.map(([k, v]) => `${pad}--${k}: ${v};`).join("\n");

const night = themed("night");
const dayOnly = themed("day").filter(([k, v], i) => v !== night[i][1]);
const fixed = [
  ["font-display", t.type.families.display],
  ["font-mono", t.type.families.mono],
  ...t.type.groups.flatMap((g) => g.styles.map((s) => [`text-${s.name}`, s.fontSize])),
  ...t.spacing.tokens.map((s) => [s.name, s.value]),
  ...t.radius.tokens.map((r) => [r.name, r.value]),
  ...t.motion.tokens.map((m) => [m.name, m.value]),
  ...t.layout.tokens.map((l) => [l.name, l.value]),
  ...t.color.palettes.flatMap((p) => p.values.map((v, i) => [`${p.name}-${i + 1}`, v])),
];
const reader = Object.entries(t.color.reader.themes).map(([id, v]) =>
  `.reader${id === "night" ? "" : `[data-theme="${id}"]`} {\n${decl(Object.entries(v).map(([k, x]) => [`r-${k}`, x]))}${id === "night" ? `\n  --r-size: ${t.color.reader.size.value};\n  color-scheme: dark;` : ""}${id === "day" ? "\n  color-scheme: light;" : ""}\n}`
).join("\n");

const css = `${HEAD}
/* Night is the default. Put data-theme="day" on <html> (or any container) for warm sand and ink. */
:root {
${decl(night)}
${decl(fixed)}
  color-scheme: dark;
}
[data-theme="day"] {
${decl(dayOnly)}
  color-scheme: light;
}

/* Reading surfaces keep their own light: night (default), dawn, day (paper). */
${reader}

@media (prefers-reduced-motion: reduce) {
  :root { --duration-fast: 0ms; --duration-base: 0ms; --duration-move: 0ms; --duration-slow: 0ms; --duration-page: 0ms; }
}
`;

const js = `${HEAD}
export const tokens = ${JSON.stringify(t, null, 2)};

/** Flat map of colour token -> value for a theme ("night" | "day"). */
export function colors(theme = "night") {
  return Object.fromEntries(tokens.color.tokens.map((c) => [c.name, typeof c.value === "string" ? c.value : c.value[theme]]));
}

export const palettes = Object.fromEntries(tokens.color.palettes.map((p) => [p.name, p.values]));
export default tokens;
`;

const out = { "tokens.css": css, "tokens.js": js };
const check = process.argv.includes("--check");
let stale = 0;
for (const [f, body] of Object.entries(out)) {
  const p = path.join(DIR, f);
  const cur = fs.existsSync(p) ? fs.readFileSync(p, "utf8") : "";
  if (cur === body) continue;
  if (check) { console.error(`stale: design-system/${f}`); stale++; }
  else { fs.writeFileSync(p, body); console.log(`wrote design-system/${f}`); }
}
if (check && stale) process.exit(1);
